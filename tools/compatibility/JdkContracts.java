import java.lang.reflect.*;
import java.nio.file.*;
import java.util.*;

/** Generate type contracts from the local JDK, never game implementations. */
public final class JdkContracts {
    private static final Set<Class<?>> contracts=new LinkedHashSet<>();
    private static String type(Class<?> c) {
        if(c.isArray())return type(c.getComponentType())+"[]";
        return (contracts.contains(c)?"port.compat.":"")+c.getCanonicalName();
    }
    public static void main(String[] args)throws Exception {
        String[] names={
            "java.io.ObjectStreamConstants",
            "java.sql.Wrapper","java.sql.Connection","java.sql.Statement","java.sql.PreparedStatement","java.sql.CallableStatement",
            "java.sql.ResultSet","java.sql.ResultSetMetaData","java.sql.DatabaseMetaData","java.sql.ParameterMetaData","java.sql.Driver",
            "java.sql.Savepoint","java.sql.Blob","java.sql.Clob","java.sql.NClob","java.sql.Array","java.sql.Ref","java.sql.RowId","java.sql.SQLXML","java.sql.Struct","java.sql.SQLType",
            "java.lang.management.PlatformManagedObject","java.lang.management.BufferPoolMXBean","java.lang.management.ClassLoadingMXBean",
            "java.lang.management.CompilationMXBean","java.lang.management.GarbageCollectorMXBean","java.lang.management.MemoryMXBean",
            "java.lang.management.MemoryPoolMXBean","java.lang.management.MemoryManagerMXBean","java.lang.management.OperatingSystemMXBean",
            "java.lang.management.RuntimeMXBean","java.lang.management.ThreadMXBean",
            "javax.management.MBeanServer","javax.management.MBeanServerConnection","javax.management.NotificationListener",
            "javax.management.NotificationEmitter","javax.management.NotificationBroadcaster","javax.management.NotificationFilter",
            "com.sun.net.httpserver.HttpHandler"
        };
        for(String name:names)contracts.add(Class.forName(name,false,JdkContracts.class.getClassLoader()));
        for(Class<?> cls:contracts) {
            if(!cls.isInterface())throw new IllegalArgumentException(cls.getName());
            StringBuilder text=new StringBuilder("// JDK 25 API signatures only, generated by tools/compatibility/JdkContracts.java.\npackage port.compat."+cls.getPackageName()+";\npublic interface "+cls.getSimpleName());
            Class<?>[] parents=cls.getInterfaces();
            if(parents.length>0){text.append(" extends ");text.append(String.join(",",Arrays.stream(parents).map(JdkContracts::type).toList()));}
            text.append(" {\n");
            for(Field field:cls.getDeclaredFields())if(Modifier.isStatic(field.getModifiers())&&field.getType().isPrimitive()){
                Object value=field.get(null);String literal=value instanceof Character c?Integer.toString(c):value.toString();
                if(field.getType()==long.class)literal+="L";else if(field.getType()==float.class)literal+="F";else if(field.getType()==double.class)literal+="D";
                text.append("    ").append(type(field.getType())).append(' ').append(field.getName()).append('=').append(literal).append(";\n");
            }
            for(Method method:Arrays.stream(cls.getDeclaredMethods()).sorted(Comparator.comparing(Method::toString)).toList()) {
                if(Modifier.isStatic(method.getModifiers())||method.isSynthetic())continue;
                // Erased API shapes match bytecode descriptors; no implementation or inferred result.
                text.append("    ").append(type(method.getReturnType())).append(' ').append(method.getName()).append('(');
                List<String> params=new ArrayList<>();int i=0;
                for(Class<?> p:method.getParameterTypes())params.add(type(p)+" arg"+i++);
                text.append(String.join(",",params)).append(')');
                if(method.getExceptionTypes().length>0)text.append(" throws ").append(String.join(",",Arrays.stream(method.getExceptionTypes()).map(JdkContracts::type).toList()));
                text.append(";\n");
            }
            text.append("}\n");
            Path file=Path.of(args[0],"port/compat",cls.getName().replace('.','/')+".java");Files.createDirectories(file.getParent());Files.writeString(file,text);
        }
        for(String name:List.of("Connection","Statement","PreparedStatement","ResultSet","DatabaseMetaData")){
            Class<?> cls=Class.forName("java.sql."+name);
            boolean prepared=name.equals("PreparedStatement");
            StringBuilder adapter=new StringBuilder("// Generated JDK signatures with explicit errors for unsupported JDBC operations.\npackage port.runtime.jdbc;\npublic abstract class Abstract"+name+(prepared?" extends BrowserStatement":"")+" implements port.compat.java.sql."+name+" {\n");
            if(prepared)adapter.append("    protected AbstractPreparedStatement(BrowserConnection connection){super(connection); }\n");
            Map<String,Method> methods=new TreeMap<>();
            for(Method method:prepared?cls.getDeclaredMethods():cls.getMethods())if(!Modifier.isStatic(method.getModifiers())&&!method.isSynthetic())methods.put(method.getName()+Arrays.toString(method.getParameterTypes()),method);
            for(Method method:methods.values()){
                adapter.append("    public ").append(type(method.getReturnType())).append(' ').append(method.getName()).append('(');int i=0;List<String> params=new ArrayList<>();for(Class<?> parameter:method.getParameterTypes())params.add(type(parameter)+" arg"+i++);adapter.append(String.join(",",params)).append(')');
                if(method.getExceptionTypes().length>0)adapter.append(" throws ").append(String.join(",",Arrays.stream(method.getExceptionTypes()).map(JdkContracts::type).toList()));
                boolean sql=Arrays.stream(method.getExceptionTypes()).anyMatch(t->t.isAssignableFrom(java.sql.SQLFeatureNotSupportedException.class));
                adapter.append(" { throw new ").append(sql?"java.sql.SQLFeatureNotSupportedException":"UnsupportedOperationException").append("(\"Browser JDBC: ").append(name).append('.').append(method.getName()).append(" is not implemented\"); }\n");
            }
            adapter.append("}\n");Path file=Path.of(args[0],"port/runtime/jdbc/Abstract"+name+".java");Files.createDirectories(file.getParent());Files.writeString(file,adapter);
        }
        System.out.println("Generated "+contracts.size()+" JDK interface contracts");
    }
}
