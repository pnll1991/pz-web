   private static final double[] EXP_POLY = new double[]{0.49999999999996786, 0.16666666666665886, 0.0416666808410674, 0.008333335853059549};
   private static final double C2 = EXP_POLY[0];
   private static final double C3 = EXP_POLY[1];
   private static final double C4 = EXP_POLY[2];
   private static final double C5 = EXP_POLY[3];

   private WasmPow() {
   }

   private static int top12(double x) {
      return (int)(Double.doubleToLongBits(x) >> 52);
   }

   private static double logInline(long ix, WasmPow.DoubleResult tail) {
      long tmp = ix - 4604531861337669632L;
      int i = (int)((tmp >>> 45) % 128L);
      int k = (int)(tmp >> 52);
      long iz = ix - (tmp & -4503599627370496L);
      double z = Double.longBitsToDouble(iz);
      double kd = k;
      double invc = tab[i].invc;
      double logc = tab[i].logc;
      double logctail = tab[i].logctail;
      double zhi = Double.longBitsToDouble(iz + 2147483648L & -4294967296L);
      double zlo = z - zhi;
      double rhi = zhi * invc - 1.0;
      double rlo = zlo * invc;
      double r = rhi + rlo;
      double t1 = kd * 0.6931471805598903 + logc;
      double t2 = t1 + r;
      double lo1 = kd * 5.497923018708371E-14 + logctail;
      double lo2 = t1 - t2 + r;
      double ar = poly[0] * r;
      double ar2 = r * ar;
      double ar3 = r * ar2;
      double arhi = poly[0] * rhi;
      double arhi2 = rhi * arhi;
      double hi = t2 + arhi2;
      double lo3 = rlo * (ar + arhi);
      double lo4 = t2 - hi + arhi2;
      double p = ar3 * (poly[1] + r * poly[2] + ar2 * (poly[3] + r * poly[4] + ar2 * (poly[5] + r * poly[6])));
      double lo = lo1 + lo2 + lo3 + lo4 + p;
      double y = hi + lo;
      tail.value = hi - y + lo;
      return y;
   }

   private static double specialcase(double tmp, long sbits, long ki) {
      if ((ki & 2147483648L) == 0L) {
         sbits -= 4544132024016830464L;
         double scale = Double.longBitsToDouble(sbits);
         return 5.486124068793689E303 * (scale + scale * tmp);
      }

      sbits += 4602678819172646912L;
      double scale = Double.longBitsToDouble(sbits);
      double y = scale + scale * tmp;
      if (Math.abs(y) < 1.0) {
         double one = 1.0;
         if (y < 0.0) {
            one = -1.0;
         }

         double lo = scale - y + scale * tmp;
         double hi = one + y;
         lo = one - hi + y + lo;
         y = hi + lo - one;
         if (y == 0.0) {
            y = Double.longBitsToDouble(sbits & Long.MIN_VALUE);
         }
      }

      return (Double.MIN_NORMAL) * y;
   }

   private static double expInline(double x, double xtail, boolean signBias) {
      int abstop = top12(x) & 2047;
      if (abstop - top12(5.551115E-17F) >= top12(512.0) - top12(5.551115E-17F)) {
         if (abstop - top12(5.551115E-17F) >= Integer.MIN_VALUE) {
            double one = 1.0 + x;
            return signBias ? -one : 1.0 + x;
         }

         if (abstop >= top12(1024.0)) {
            if (Double.doubleToLongBits(x) >>> 63 != 0L) {
               return mathUflow(signBias);
            }

            return mathOflow(signBias);
         }

         abstop = 0;
      }

      double z = 184.6649652337873 * x;
      double kd = z + 6.7553994E15F;
      long ki = Double.doubleToLongBits(kd);
      kd -= 6.7553994E15F;
      double r = x + kd * -0.005415212348111709 + kd * -1.2864023111638346E-14;
      r += xtail;
      long idx = 2L * (ki % 128L);
      long top = ki + (signBias ? 1 : 0) << 45;
      double tail = Double.longBitsToDouble(EXP_TAB[(int)idx]);
      long sbits = EXP_TAB[(int)idx + 1] + top;
      double r2 = r * r;
      double tmp = tail + r + r2 * (C2 + r * C3) + r2 * r2 * (C4 + r * C5);
      if (abstop == 0) {
         return specialcase(tmp, sbits, ki);
      }

      double scale = Double.longBitsToDouble(sbits);
      return scale + scale * tmp;
   }

   private static double mathOflow(boolean sign) {
      return mathXflow(sign, 3.105036184601418E231);
   }

   private static double mathUflow(boolean sign) {
      return mathXflow(sign, 1.2882297539194267E-231);
   }

   private static double mathXflow(boolean sign, double y) {
      return (sign ? -y : y) * y;
   }

   private static int checkint(long iy) {
      int e = (int)(iy >>> 52 & 2047L);
      if (e < 1023) {
         return 0;
      } else if (e > 1075) {
         return 2;
      } else if ((iy & (1L << 1075 - e) - 1L) != 0L) {
         return 0;
      } else {
         return (iy & 1L << 1075 - e) != 0L ? 1 : 2;
      }
   }

   private static boolean zeroinfnan(long i) {
      return 2L * i - 1L >= 2L * Double.doubleToLongBits(Double.POSITIVE_INFINITY) - 1L;
   }

   public static double pow(double x, double y) {
      boolean signBias = false;
      long ix = Double.doubleToLongBits(x);
      long iy = Double.doubleToLongBits(y);
      int topx = top12(x);
      int topy = top12(y);
      if (topx - 1 >= 2046 || (topy & 2047) - 958 >= 128) {
         if (zeroinfnan(iy)) {
            if (2L * iy == 0L) {
               return 1.0;
            }

            if (ix == Double.doubleToLongBits(1.0)) {
               return 1.0;
            }

            if (2L * ix <= 2L * Double.doubleToLongBits(Double.POSITIVE_INFINITY) && 2L * iy <= 2L * Double.doubleToLongBits(Double.POSITIVE_INFINITY)) {
               if (2L * ix == 2L * Double.doubleToLongBits(1.0)) {
                  return 1.0;
               }

               if (2L * ix < 2L * Double.doubleToLongBits(1.0) == (iy >>> 63 == 0L)) {
                  return 0.0;
               }

               return y * y;
            }

            return x + y;
         }

         if (zeroinfnan(ix)) {
            double x2 = x * x;
            if (ix >>> 63 != 0L && checkint(iy) == 1) {
               x2 = -x2;
            }

            return iy >>> 63 != 0L ? 1.0 / x2 : x2;
         }

         if (ix >>> 63 != 0L) {
            int yint = checkint(iy);
            if (yint == 0) {
               return x;
            }

            if (yint == 1) {
               signBias = true;
            }

            ix &= Long.MAX_VALUE;
            topx &= 2047;
         }

         if ((topy & 2047) - 958 >= 128) {
            if (ix == Double.doubleToLongBits(1.0)) {
               return 1.0;
            }

            if ((topy & 2047) < 958) {
               return 1.0;
            }

            return ix > Double.doubleToLongBits(1.0) == topy < 2048 ? mathOflow(false) : mathUflow(false);
         }

         if (topx == 0) {
            ix = Double.doubleToLongBits(x * 4.5035996E15F);
            ix &= Long.MAX_VALUE;
            ix -= 234187180623265792L;
         }
      }

      WasmPow.DoubleResult lo = new WasmPow.DoubleResult();
      double hi = logInline(ix, lo);
      double yhi = Double.longBitsToDouble(iy & -134217728L);
      double ylo = y - yhi;
      double lhi = Double.longBitsToDouble(Double.doubleToLongBits(hi) & -134217728L);
      double llo = hi - lhi + lo.value;
      double ehi = yhi * lhi;
      double elo = ylo * lhi + y * llo;
      return expInline(ehi, elo, signBias);
   }

   private static WasmPow.TableEntry a(double a, double b, double c) {
      WasmPow.TableEntry entry = new WasmPow.TableEntry();
      entry.invc = a;
      entry.logc = b;
      entry.logctail = c;
      return entry;
   }

